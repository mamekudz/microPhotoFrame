#!/usr/bin/env node
/**
 * Erzeugt firmware/include/embedded_branding_ink.h
 * Nutzt das lokale Paket ink-encoder (Format v1–v3 wie Firmware) — keine doppelte Codec-Logik.
 *
 * Quellen (optional): webassets/Logo.png + webassets/LogoText.png
 * Fehlen die Dateien → SVG-Platzhalter (trotzdem gültig).
 *
 * Voraussetzung: npm install im Projektroot (ink-encoder per file:../ink-encoder).
 *
 * Ausführung: npm run gen:branding
 * Display-ID: Umgebungsvariable EMBED_DISPLAY_ID (Standard: I)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';
import { EncodeInk, GetOptionsFromDisplayId } from 'ink-encoder';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT_H = path.join(ROOT, 'firmware', 'include', 'embedded_branding_ink.h');

const W = 800;
const H = 480;
const DISPLAY_ID = (process.env.EMBED_DISPLAY_ID || 'I').trim().charAt(0);

async function buildPng800x480() {
  const logoPath = path.join(ROOT, 'webassets', 'Logo.png');
  const textPath = path.join(ROOT, 'webassets', 'LogoText.png');
  const base = sharp({
    create: { width: W, height: H, channels: 3, background: { r: 255, g: 255, b: 255 } },
  }).png();

  const composites = [];
  if (fs.existsSync(logoPath)) {
    const meta = await sharp(logoPath).metadata();
    const lw = meta.width || 200;
    const lh = meta.height || 200;
    const maxLogoW = Math.floor(W * 0.42);
    const maxLogoH = 200;
    const scale = Math.min(maxLogoW / lw, maxLogoH / lh, 1);
    const tw = Math.round(lw * scale);
    const th = Math.round(lh * scale);
    const logoBuf = await sharp(logoPath).resize(tw, th, { fit: 'inside' }).ensureAlpha().toBuffer();
    composites.push({ input: logoBuf, left: Math.floor((W - tw) / 2), top: 36 });
  }
  if (fs.existsSync(textPath)) {
    const meta = await sharp(textPath).metadata();
    const lw = meta.width || 300;
    const lh = meta.height || 60;
    const maxTW = Math.floor(W * 0.85);
    const maxTH = 100;
    const scale = Math.min(maxTW / lw, maxTH / lh, 1);
    const tw = Math.round(lw * scale);
    const th = Math.round(lh * scale);
    const textBuf = await sharp(textPath).resize(tw, th, { fit: 'inside' }).ensureAlpha().toBuffer();
    const top = composites.length ? 36 + 200 + 16 : 200;
    composites.push({ input: textBuf, left: Math.floor((W - tw) / 2), top });
  }

  if (composites.length === 0) {
    const svg = `<svg width="${W}" height="${H}">
      <rect x="80" y="120" width="${W - 160}" height="200" fill="none" stroke="#000" stroke-width="4"/>
      <text x="400" y="240" text-anchor="middle" font-family="sans-serif" font-size="28" fill="#000">µPhotoFrame</text>
    </svg>`;
    return sharp(Buffer.from(svg)).resize(W, H).png().toBuffer();
  }

  return base.composite(composites).png().toBuffer();
}

async function main() {
  const pngBuf = await buildPng800x480();
  const opts = GetOptionsFromDisplayId(DISPLAY_ID, {
    compression: 'deflatePaeth',
    dither: 'floyd',
  });
  const ink = await EncodeInk(pngBuf, opts);

  const lines = [
    '/* Auto-generated by tools/gen-embedded-branding.mjs — do not edit */',
    '#pragma once',
    '#include <Arduino.h>',
    '',
    `// .ink via ink-encoder (Display '${DISPLAY_ID}'), ${ink.length} bytes`,
    `static const uint8_t kEmbeddedBrandingInk[] PROGMEM = {`,
  ];

  const row = [];
  for (let i = 0; i < ink.length; i++) {
    row.push(`0x${ink[i].toString(16).padStart(2, '0')}`);
    if (row.length >= 16 || i === ink.length - 1) {
      lines.push('  ' + row.join(', ') + (i === ink.length - 1 ? '' : ','));
      row.length = 0;
    }
  }
  lines.push('};');
  lines.push(`static constexpr size_t kEmbeddedBrandingInkSize = ${ink.length};`);
  lines.push('');

  fs.mkdirSync(path.dirname(OUT_H), { recursive: true });
  fs.writeFileSync(OUT_H, lines.join('\n') + '\n', 'utf8');
  console.log('Written', path.relative(ROOT, OUT_H), `(${ink.length} bytes)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
